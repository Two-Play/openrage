#!/usr/bin/env python3
"""Regenerates the licences of OpenRAGE's dependencies from Cargo.lock.

Writes
  * THIRD_PARTY_LICENSES.md (shipped with every release), and
  * crates/openrage-app/src/third_party_licenses.json (shown in the app's
    About dialog, by `openrage licenses` and on the website).

Needs cargo-about (`cargo install --locked --features cli cargo-about`).
Run it after changing dependencies; `--check` (used by CI) fails when the
committed files are out of date. Licence texts come only from the crates
themselves (`cargo about generate --frozen`), so the result is the same on
every machine.
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MARKDOWN = ROOT / "THIRD_PARTY_LICENSES.md"
DATA = ROOT / "crates" / "openrage-app" / "src" / "third_party_licenses.json"


def about_json() -> dict:
    out = subprocess.run(
        ["cargo", "about", "generate", "--frozen", "--workspace", "--fail", "--format", "json"],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return json.loads(out)


def collect(about: dict) -> dict:
    """Licence texts (deduplicated) and the crates that use them, without
    OpenRAGE's own crates and without local paths."""
    texts: list[dict] = []
    index: dict[tuple[str, str], int] = {}
    uses: dict[str, list[int]] = {}
    for lic in about["licenses"]:
        # Some crates ship their licence with Windows line endings.
        text = lic["text"].replace("\r\n", "\n").replace("\r", "\n")
        key = (lic["id"], text)
        if key not in index:
            index[key] = len(texts)
            texts.append({"id": lic["id"], "name": lic["name"], "text": text})
        for used in lic["used_by"]:
            crate = used["crate"]
            if crate["source"] is None:
                continue
            uses.setdefault(crate["id"], []).append(index[key])
    crates = []
    for entry in about["crates"]:
        pkg = entry["package"]
        if pkg["source"] is None:
            continue
        crates.append(
            {
                "name": pkg["name"],
                "version": pkg["version"],
                "license": pkg.get("license") or entry["license"],
                "repository": pkg.get("repository") or pkg.get("homepage") or "",
                "texts": sorted(set(uses.get(pkg["id"], []))),
            }
        )
    crates.sort(key=lambda c: (c["name"].lower(), c["version"]))
    # Keep only texts some third-party crate uses, renumbered.
    used = sorted({t for c in crates for t in c["texts"]})
    renumber = {old: new for new, old in enumerate(used)}
    for c in crates:
        c["texts"] = [renumber[t] for t in c["texts"]]
    return {"crates": crates, "licenses": [texts[t] for t in used]}


def markdown(data: dict) -> str:
    crates, texts = data["crates"], data["licenses"]
    out = [
        "# Third-party licenses",
        "",
        "OpenRAGE is licensed under the GPL-3.0-only (see `LICENSE`); `crates/rage-tfit2` under the",
        "AGPL-3.0-only. Credits for format knowledge and ported code are in `NOTICE.md`.",
        "",
        f"The OpenRAGE programs contain the following {len(crates)} Rust crates. Their license texts",
        "follow, each with the crates it applies to.",
        "",
        "This file is generated by `dev/third_party_licenses.py`; do not edit it by hand.",
        "",
        "## Crates",
        "",
        "| Crate | Version | License |",
        "|---|---|---|",
    ]
    for c in crates:
        name = f"[{c['name']}]({c['repository']})" if c["repository"] else c["name"]
        out.append(f"| {name} | {c['version']} | {c['license']} |")
    out += ["", "## License texts", ""]
    for i, t in enumerate(texts):
        users = [f"{c['name']} {c['version']}" for c in crates if i in c["texts"]]
        out += [
            f"### {t['name']} ({t['id']}) #{i + 1}",
            "",
            "Used by: " + ", ".join(users),
            "",
            "~~~~text",
            t["text"].rstrip(),
            "~~~~",
            "",
        ]
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the committed files are out of date")
    args = parser.parse_args()
    data = collect(about_json())
    files = {
        MARKDOWN: markdown(data),
        DATA: json.dumps(data, ensure_ascii=False, separators=(",", ":")) + "\n",
    }
    if args.check:
        stale = [p for p, content in files.items() if not p.exists() or p.read_bytes() != content.encode()]
        for p in stale:
            print(f"{p.relative_to(ROOT)} is out of date: run python3 dev/third_party_licenses.py", file=sys.stderr)
        return 1 if stale else 0
    for p, content in files.items():
        p.write_bytes(content.encode())
        print(f"wrote {p.relative_to(ROOT)}")
    print(f"{len(data['crates'])} crates, {len(data['licenses'])} license texts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
