pub static SKIP_VLC: [Vlc; 2] = [vlc(&SKIP_CODES[0], &SKIP_BITS[0]), vlc(&SKIP_CODES[1], &SKIP_BITS[1])];
pub static MV_VLC: Vlc = vlc(&MV_CODES, &MV_BITS);

#[cfg(test)]
mod tests {
    use super::*;

    /// No code is the start of another one.
    #[test]
    fn prefix_free() {
        fn check(codes: &[u16], bits: &[u8], table: &Vlc) {
            for (i, (&c, &b)) in codes.iter().zip(bits).enumerate() {
                for (j, (&d, &e)) in codes.iter().zip(bits).enumerate() {
                    assert!(i == j || b > e || c != d & ((1 << b) - 1), "{i} is a prefix of {j}");
                }
                assert_eq!(table[c as usize], (i as u8, b));
            }
        }
        check(&SKIP_CODES[0], &SKIP_BITS[0], &SKIP_VLC[0]);
        check(&SKIP_CODES[1], &SKIP_BITS[1], &SKIP_VLC[1]);
        check(&MV_CODES, &MV_BITS, &MV_VLC);
    }

    #[test]
    fn scan_is_a_permutation() {
        let mut seen = [false; 64];
        SCAN.iter().for_each(|&i| seen[i as usize] = true);
        assert!(seen.iter().all(|&s| s));
    }
}
