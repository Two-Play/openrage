/// Symbol and code length by the next 9 bits; length 0: no such code.
pub type Vlc = [(u8, u8); 512];

const fn vlc<const N: usize>(codes: &[u16; N], bits: &[u8; N]) -> Vlc {
    let mut out = [(0, 0); 512];
    let mut i = 0;
    while i < 512 {
        let mut s = 0;
        while s < N {
            if i & ((1 << bits[s]) - 1) == codes[s] as usize {
                out[i] = (s as u8, bits[s]);
            }
            s += 1;
        }
        i += 1;
    }
    out
}

